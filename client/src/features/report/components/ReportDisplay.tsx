import { DataTable, DataTableColumn } from '../../../components/ui/data-table';
import { Button } from '../../../components';
import { cn } from '../../../utils/cn';
import { formatCurrency } from '../../../utils/number';
import {
  ProductSale,
  Report,
  ReportExpense,
  ReportUser,
} from '../../../services/report/report.types';
import { PaymentType } from '../../../services/transaction/transaction.types';
import { useRemit } from '../../../services/report/report.queries';
import { Trash } from 'lucide-react';
import { UserRole } from '../../../types';
import { useAuthContext } from '../../../context/auth/useAuthContext';

type PreviewReport = Pick<
  Report,
  | 'products'
  | 'totalCash'
  | 'totalOnline'
  | 'totalIncome'
  | 'totalExpenses'
  | 'totalPrintCount'
> & {
  id?: string;
  createdBy?: ReportUser;
  fromDate?: string;
  toDate?: string;
  createdAt?: string;
  expenses?: ReportExpense[];
  isRemitted?: boolean;
};

interface Props {
  report: PreviewReport;
  isPreview?: boolean;
  onDelete?: (id: string) => void;
}

const formatDate = (iso: string) =>
  new Date(iso).toLocaleString('en-PH', {
    dateStyle: 'medium',
    timeStyle: 'short',
  });

const productColumns: DataTableColumn<ProductSale>[] = [
  {
    id: 'name',
    heading: 'Product',
    orderable: true,
    cell: (p) => p.name,
  },
  {
    id: 'quantitySold',
    heading: 'Qty Sold',
    cell: (p) => p.quantitySold,
  },
  {
    id: 'pricePerUnit',
    heading: 'Price / Unit',
    cell: (p) => formatCurrency(p.pricePerUnit),
  },
  {
    id: 'total',
    heading: 'Total',
    cell: (p) => <span className="font-medium">{formatCurrency(p.total)}</span>,
  },
];

const expenseColumns: DataTableColumn<ReportExpense>[] = [
  {
    id: 'label',
    heading: 'Label',
    cell: (e) => e.label,
  },
  {
    id: 'paymentType',
    heading: 'Payment',
    cell: (e) => (e.paymentType === PaymentType.Cash ? 'Cash' : 'Online'),
  },
  {
    id: 'total',
    heading: 'Amount',
    cell: (e) => <span className="font-medium">{formatCurrency(e.total)}</span>,
  },
];

export const ReportDisplay = ({ report, isPreview, onDelete }: Props) => {
  const remit = useRemit();
  const { auth } = useAuthContext();

  return (
    <div className="flex flex-col gap-4">
      <div
        className={`flex flex-col gap-6 rounded-md border bg-white p-6 ${isPreview ? 'border-dashed opacity-70' : ''}`}
      >
        {isPreview && (
          <div className="rounded-md bg-slate-100 px-3 py-2 text-center text-xs font-medium text-slate-500">
            Preview — report not yet generated
          </div>
        )}

        {!isPreview && (report.createdBy || report.createdAt) && (
          <div className="flex flex-row items-start justify-between">
            <div className="flex flex-col gap-1">
              {report.createdBy && report.createdAt && (
                <p className="text-sm text-slate-500">
                  Generated by{' '}
                  <span className="font-medium text-slate-800">
                    {report.createdBy.username}
                  </span>{' '}
                  on {formatDate(report.createdAt)}
                </p>
              )}
              {report.fromDate && report.toDate && (
                <p className="text-sm text-slate-500">
                  Period: {formatDate(report.fromDate)} —{' '}
                  {formatDate(report.toDate)}
                </p>
              )}
            </div>
            <div className="flex items-center gap-2">
              {report.id && (
                <>
                  <span className="flex items-center gap-1.5 rounded-sm border px-2 py-1 text-xs font-medium">
                    <span
                      className={cn(
                        'h-2 w-2 shrink-0 rounded-full',
                        report.isRemitted ? 'bg-green-500' : 'bg-gray-400',
                      )}
                    />
                    {report.isRemitted ? 'Remitted' : 'Not Remitted'}
                  </span>
                  <Button
                    hidden={auth?.role !== UserRole.ADMIN}
                    type="button"
                    variant="outline"
                    size="xs"
                    disabled={remit.isPending}
                    onClick={() =>
                      remit.mutate({
                        id: report.id!,
                        isRemitted: !report.isRemitted,
                      })
                    }
                  >
                    {report.isRemitted ? 'Undo Remit' : 'Mark as Remitted'}
                  </Button>
                </>
              )}
              {onDelete && report.id && (
                <button
                  type="button"
                  onClick={() => onDelete(report.id!)}
                  className="text-muted-foreground hover:bg-muted hover:text-foreground rounded-md p-1 transition-colors"
                  aria-label="Delete report"
                >
                  <Trash size={16} />
                </button>
              )}
            </div>
          </div>
        )}

        <div className="grid grid-cols-2 gap-4 sm:grid-cols-3 lg:grid-cols-5">
          <div className="flex flex-col gap-1 rounded-md border bg-slate-50 p-4">
            <span className="text-xs font-medium text-slate-500">Cash</span>
            <span className="text-foreground text-xl font-bold">
              {formatCurrency(report.totalCash)}
            </span>
          </div>
          <div className="flex flex-col gap-1 rounded-md border bg-slate-50 p-4">
            <span className="text-xs font-medium text-slate-500">Online</span>
            <span className="text-foreground text-xl font-bold">
              {formatCurrency(report.totalOnline)}
            </span>
          </div>
          <div className="flex flex-col gap-1 rounded-md border bg-slate-50 p-4">
            <span className="text-xs font-medium text-slate-500">Expenses</span>
            <span className="text-foreground text-xl font-bold">
              {formatCurrency(report.totalExpenses)}
            </span>
          </div>
          <div className="flex flex-col gap-1 rounded-md border bg-blue-50 p-4">
            <span className="text-xs font-medium text-blue-600">
              Total Income
            </span>
            <span className="text-xl font-bold text-blue-700">
              {formatCurrency(report.totalIncome)}
            </span>
          </div>
          <div className="flex flex-col gap-1 rounded-md border bg-slate-50 p-4">
            <span className="text-xs font-medium text-slate-500">
              Total Prints
            </span>
            <span className="text-foreground text-xl font-bold">
              {report.totalPrintCount.toLocaleString()}
            </span>
          </div>
        </div>

        <div className="flex flex-col gap-3">
          <h3 className="text-sm font-semibold text-slate-700">
            Products Sold
          </h3>
          <DataTable
            collection={DataTable.collection({
              items: report.products,
              itemToValue: (p) => p.productId,
              itemToString: (p) => p.name,
            })}
            columns={productColumns}
            emptyMessage="No transactions found in this date range."
          />
        </div>

        {!isPreview && report.id && (
          <div className="flex flex-col gap-3">
            <h3 className="text-sm font-semibold text-slate-700">Expenses</h3>
            <DataTable
              collection={DataTable.collection({
                items: report.expenses ?? [],
                itemToValue: (e) => e.id,
                itemToString: (e) => e.label ?? e.id,
              })}
              columns={expenseColumns}
              emptyMessage="No expenses logged in this date range."
            />
          </div>
        )}
      </div>
    </div>
  );
};
